#!/usr/bin/env python3
"""Report drift between the Swift-visible legacy collection header and its generator.

The legacy iOS 5 profile ships `usr/lib/swift_ios5/legacy-collection/Headers/UIKitLegacyCollection.h`,
generated by `generate-collection-headers.py`. When the backport's headers change, that resource goes stale and
Swift code compiled for iOS 5 sees an older API surface than the ObjC route. This checks one against the other.

Usage: check-legacy-swift-resource.py [--toolchain X.xctoolchain] [--source PSTCollectionView dir]
Exits 0 when in sync, 1 on drift (with a summary), 2 when the resource is not installed.
"""
import argparse, difflib, pathlib, subprocess, sys, tempfile

HERE = pathlib.Path(__file__).resolve().parent
REL = 'usr/lib/swift_ios5/legacy-collection/Headers/UIKitLegacyCollection.h'

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--toolchain', default=str(pathlib.Path.home() /
        'Library/Developer/Toolchains/LegacySwiftDevelopmentKit-monterey-modern-5.10.1.xctoolchain'))
    ap.add_argument('--source', default=str(HERE / 'vendor/PSTCollectionView'))
    args = ap.parse_args()
    installed = pathlib.Path(args.toolchain) / REL
    if not installed.is_file():
        print(f'not installed: {installed}')
        return 2
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp)
        subprocess.run([sys.executable, str(HERE / 'generate-collection-headers.py'), args.source, str(out)],
                       check=True, capture_output=True, text=True)
        expected = (out / 'UIKitLegacyCollection.h').read_text()
    actual = installed.read_text()
    if actual == expected:
        print(f'in sync: {installed}')
        return 0
    diff = list(difflib.unified_diff(actual.splitlines(), expected.splitlines(),
                                     'installed', 'generated', n=0, lineterm=''))
    # In this diff `-` is present only in the installed (stale) header and `+` only in the generated one.
    only_installed = [l[1:] for l in diff if l.startswith('-') and not l.startswith('---')]
    only_generated = [l[1:] for l in diff if l.startswith('+') and not l.startswith('+++')]
    print(f'DRIFT: {installed}')
    print(f'  installed={len(actual.splitlines())} lines, generated={len(expected.splitlines())} lines')
    print(f'  missing from the installed resource: {len(only_generated)} lines,'
          f' present only there: {len(only_installed)} lines')
    for l in only_generated:
        s = l.strip()
        if s.startswith(('@protocol', '@interface', '@property')) or s.startswith('- ('):
            print(f'    + {s}')
    print('  republish with publish-ios5-profile.py (needs qualification evidence)')
    return 1

if __name__ == '__main__':
    sys.exit(main())
