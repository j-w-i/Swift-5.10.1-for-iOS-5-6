#!/usr/bin/env python3
"""Generate true UIKit declarations with linkable compatibility runtime names."""
import argparse
from pathlib import Path
import re

PUBLIC = ('PSTCollectionViewCommon.h', 'PSTCollectionViewLayout.h',
          'PSTCollectionViewFlowLayout.h', 'PSTCollectionViewCell.h',
          'PSTCollectionViewController.h', 'PSTCollectionViewUpdateItem.h',
          'PSTCollectionView.h', 'NSIndexPath+PSTCollectionViewAdditions.h')
WRAPPERS = ('UICollectionView', 'UICollectionViewCell', 'UICollectionReusableView',
            'UICollectionViewLayout', 'UICollectionViewFlowLayout',
            'UICollectionViewLayoutAttributes', 'UICollectionViewController',
            'UICollectionViewUpdateItem', 'UICollectionViewLayoutInvalidationContext',
             'UICollectionViewFlowLayoutInvalidationContext')

def generate(source, output):
    output.mkdir(parents=True, exist_ok=True)
    pieces = ['// Generated by generate-collection-headers.py; do not edit.\n'
              '// MIT Peter Steinberger; see ../LICENSE.\n#pragma once\n'
              '#import <Foundation/Foundation.h>\n'
              '#import <CoreGraphics/CoreGraphics.h>\n'
              '#import <QuartzCore/QuartzCore.h>\n'
              '#import <UIKit/UIScrollView.h>\n'
              '#import <UIKit/UIViewController.h>\n'
              '#import <UIKit/UINib.h>\n']
    for name in PUBLIC:
        text = (source / name).read_text()
        # UIKit.h has already imported the non-collection UIKit declarations.
        text = re.sub(r'^#import .*\n', '', text, flags=re.M)
        text = re.sub(r'__attribute__\(\(swift_name\("[^"]+"\)\)\)\n', '', text)
        if name == 'PSTCollectionView.h':
            text = text.split('// To dynamically switch')[0]
        text = text.replace('PSTCollection', 'UICollection')
        if name == 'PSTCollectionViewLayout.h':
            text = text.replace('UICollectionViewItemType', 'UICollectionElementCategory')
        if name == 'PSTCollectionView.h':
            text = re.sub(r'typedef NS_ENUM\(NSUInteger, UICollectionElementCategory\) \{.*?\};', '', text, flags=re.S)
        # Protocol identities must match the formal protocols in runtime objects.
        text = re.sub(r'(@protocol (UICollection\w+) <)',
                      lambda m: '__attribute__((objc_runtime_name("' + m[2].replace('UICollection', 'PSTCollection') + '")))\n' + m[1], text)
        for cls in WRAPPERS:
            text = re.sub(r'(@interface ' + cls + r'\s*:)',
                          '__attribute__((objc_runtime_name("' + cls.replace('UICollection', 'PSTCollection') + '")))\n' + r'\1', text)
        # This header is the Swift-visible surface for iOS 5: it must describe UIKit, not the backport's
        # implementation. Drop the internal pst* helpers and the SelfSizing category they live in.
        text = re.sub(r'^[^\n]*\bpst[A-Z]\w*[^\n]*\n', '', text, flags=re.M)
        text = re.sub(r'@interface (UICollection\w+) \(SelfSizing\)\n(?:[^@]*?\n)?@end\n', '', text)
        # Preserve C symbol linkage while exposing UIKit source spelling.
        text = re.sub(r'extern NSString \*const (UICollection\w+);',
                      lambda m: 'extern NSString *const ' + m[1] + ' __asm__("_' + m[1].replace('UICollection', 'PSTCollection') + '");', text)
        pieces.append('// From ' + name + '\n' + text + '\n')
    (output / 'UIKitLegacyCollection.h').write_text('\n'.join(pieces))

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    generate(args.source, args.output)
