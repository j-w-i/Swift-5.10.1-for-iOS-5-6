#!/bin/bash
set -euo pipefail
B="$HOME/swift-5.10-ios5-build"
export DEVELOPER_DIR="$HOME/Applications/Xcode-13.4.1.app/Contents/Developer"
HOST="$HOME/Library/Developer/Toolchains/swift-5.10.1-RELEASE.xctoolchain/usr/bin/swiftc"
SDK="$DEVELOPER_DIR/Platforms/iPhoneOS.platform/Developer/SDKs/iPhoneOS15.5.sdk"
R="$B/probes/modules510"
ORIGINAL="$B/probes/foundation510-sources.txt"
# Rewrite only source paths in the baseline response list; use isolated migrated copies.
sed "s|$HOME/swift-ios5-build/src/swift/stdlib/public/Darwin/Foundation/|$B/src/legacy-overlays/Foundation/|g" "$HOME/swift-ios5-build/build/runtime-ios5/stdlib/public/Darwin/Foundation/ursnm.txt" > "$ORIGINAL"
mkdir -p "$R/iphoneos/Foundation.swiftmodule"
# Source list is generated by the previous complete legacy build; treat as response-file data, not executable shell.
exec /usr/bin/nice -n 15 /usr/bin/arch -x86_64 "$HOST" -j1 -parse-as-library -module-name Foundation \
 -target armv7-apple-ios7.0 -sdk "$SDK" -resource-dir "$R" -D LEGACY_IOS5 \
 -I "$B/probes/dispatch-shims" -Xcc -I"$R/iphoneos" \
 -enable-library-evolution -O -whole-module-optimization -emit-object -o "$B/probes/Foundation510.o" -emit-module -emit-module-path "$R/iphoneos/Foundation.swiftmodule/armv7.swiftmodule" \
 -runtime-compatibility-version none -disable-autolinking-runtime-compatibility-dynamic-replacements \
 -module-link-name swiftFoundation -swift-version 5 @"$ORIGINAL"
